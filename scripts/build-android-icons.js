import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

console.log('🚀 Running Fundora Native Android Icon Generator...');

const SRC_JPG = 'src/assets/images/fundora_logo_1784832076498.jpg';

if (!fs.existsSync(SRC_JPG)) {
  console.error('❌ Source logo file not found at:', SRC_JPG);
  process.exit(1);
}

// 1. Prepare high quality Fundora symbol with transparent background
try {
  execSync('convert -version', { stdio: 'ignore' });
} catch {
  console.log('⚠️ ImageMagick (convert) is not installed in this environment.');
  console.log(' Skipping dynamic icon generation. Existing pre-generated icons in android/app/src/main/res/ will be used.');
  process.exit(0);
}

try {
  execSync(`convert ${SRC_JPG} -fuzz 10% -trim +repage /tmp/fundora_trimmed.png`);
  execSync(`convert /tmp/fundora_trimmed.png -fuzz 12% -transparent white PNG32:/tmp/fundora_symbol.png`);
} catch (err) {
  console.warn('⚠️ Could not process source image with ImageMagick:', err.message);
  console.log(' Continuing with existing pre-generated icons in res/.');
  process.exit(0);
}

// 2. Android Adaptive Foreground sizes (108dp base grid)
const ADAPTIVE_FOREGROUND = {
  mdpi: 108,
  hdpi: 162,
  xhdpi: 216,
  xxhdpi: 324,
  xxxhdpi: 432
};

// 3. Legacy Launcher sizes (mdpi=48, hdpi=72, xhdpi=96, xxhdpi=144, xxxhdpi=192)
const LEGACY_LAUNCHER = {
  mdpi: 48,
  hdpi: 72,
  xhdpi: 96,
  xxhdpi: 144,
  xxxhdpi: 192
};

// Cleanup old obsolete or buggy files
const resDir = path.join('android', 'app', 'src', 'main', 'res');

if (fs.existsSync(path.join(resDir, 'mipmap-ldpi'))) {
  fs.rmSync(path.join(resDir, 'mipmap-ldpi'), { recursive: true, force: true });
}

// Remove any ic_launcher_background.png generated by @capacitor/assets
for (const density of Object.keys(ADAPTIVE_FOREGROUND)) {
  const bgFile = path.join(resDir, `mipmap-${density}`, 'ic_launcher_background.png');
  if (fs.existsSync(bgFile)) {
    fs.unlinkSync(bgFile);
  }
}

// Generate Adaptive Foregrounds
for (const [density, canvas] of Object.entries(ADAPTIVE_FOREGROUND)) {
  const dir = path.join(resDir, `mipmap-${density}`);
  fs.mkdirSync(dir, { recursive: true });

  const inner = Math.round(canvas * 0.62); // 62% zone ensures no clipping in circles/squircles
  execSync(`convert /tmp/fundora_symbol.png -resize ${inner}x${inner} -gravity center -background transparent -extent ${canvas}x${canvas} PNG32:${path.join(dir, 'ic_launcher_foreground.png')}`);
}

// Generate Legacy & Round Icons
for (const [density, size] of Object.entries(LEGACY_LAUNCHER)) {
  const dir = path.join(resDir, `mipmap-${density}`);
  fs.mkdirSync(dir, { recursive: true });

  const inner = Math.round(size * 0.85);

  // Square / Standard legacy icon
  execSync(`convert /tmp/fundora_symbol.png -resize ${inner}x${inner} -gravity center -background "#030514" -extent ${size}x${size} PNG32:${path.join(dir, 'ic_launcher.png')}`);

  // Round legacy icon
  execSync(`convert /tmp/fundora_symbol.png -resize ${inner}x${inner} -gravity center -background "#030514" -extent ${size}x${size} PNG32:${path.join(dir, 'ic_launcher_round.png')}`);
}

// 4. Update ic_launcher_background.xml
const valuesDir = path.join(resDir, 'values');
fs.mkdirSync(valuesDir, { recursive: true });
fs.writeFileSync(
  path.join(valuesDir, 'ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#030514</color>\n</resources>\n`
);

// 5. Update mipmap-anydpi-v26/ic_launcher.xml & ic_launcher_round.xml
const anyDpiDir = path.join(resDir, 'mipmap-anydpi-v26');
fs.mkdirSync(anyDpiDir, { recursive: true });

const adaptiveXml = `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background" />\n    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n</adaptive-icon>\n`;

fs.writeFileSync(path.join(anyDpiDir, 'ic_launcher.xml'), adaptiveXml);
fs.writeFileSync(path.join(anyDpiDir, 'ic_launcher_round.xml'), adaptiveXml);

console.log('✅ Fundora Native Android Icons generated successfully!');
